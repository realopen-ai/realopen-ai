"""Optional Ollama CLI import for native MLX weights on Apple Silicon.

Ollama versions expose this as a local-only experimental creation workflow;
never send it to a remote server or substitute/requantize model weights.
"""

import asyncio
import os
import platform
import re
import shutil
import signal
from urllib.parse import urlsplit

from .downloads import cache_root
from .types import ModelManagerError


def candidate(base_url):
    url = urlsplit(base_url)
    return (
        platform.system() == "Darwin"
        and platform.machine().lower() in {"arm64", "aarch64"}
        and url.hostname in {"localhost", "127.0.0.1", "::1"}
        and shutil.which("ollama") is not None
    )


async def supported(base_url):
    if not candidate(base_url):
        return False
    try:
        process = await asyncio.create_subprocess_exec(
            "ollama",
            "create",
            "--help",
            stdout=asyncio.subprocess.PIPE,
            stderr=asyncio.subprocess.STDOUT,
        )
        output, _ = await asyncio.wait_for(process.communicate(), 5)
        return process.returncode == 0 and b"--experimental" in output
    except (OSError, asyncio.TimeoutError):
        if "process" in locals() and process.returncode is None:
            process.kill()
            await process.wait()
        return False


async def install(base_url, model, name, *, modelfile=None):
    directory = cache_root(model)
    # Only a FROM directive generated by us; repository Modelfiles/scripts
    # are never executed. No --quantize flag: preserve original weights.
    if modelfile is None:
        modelfile = directory / "RealOpen.Modelfile"
        modelfile.write_text("FROM .\n", encoding="utf-8")
    process = await asyncio.create_subprocess_exec(
        "ollama",
        "create",
        name,
        "--experimental",
        "-f",
        str(modelfile),
        cwd=directory,
        env={**os.environ, "OLLAMA_HOST": base_url},
        stdout=asyncio.subprocess.PIPE,
        stderr=asyncio.subprocess.STDOUT,
        start_new_session=True,
    )
    try:
        while True:
            data = await process.stdout.read(4096)
            if not data:
                break
            text = re.sub(
                r"\x1b\[[0-?]*[ -/]*[@-~]", "", data.decode("utf-8", errors="replace")
            )
            lines = [
                line.strip()
                for line in text.replace("\r", "\n").splitlines()
                if line.strip()
            ]
            if lines:
                yield {"stage": "importing", "message": lines[-1][:180]}
        if await process.wait() != 0:
            raise ModelManagerError(
                "Local Ollama import failed. Check the host runtime log and model architecture compatibility."
            )
    finally:
        if process.returncode is None:
            os.killpg(process.pid, signal.SIGTERM)
            try:
                await asyncio.wait_for(process.wait(), 5)
            except asyncio.TimeoutError:
                os.killpg(process.pid, signal.SIGKILL)
                await process.wait()
