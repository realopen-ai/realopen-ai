def _validate_excel_custom(custom: Dict[str, Any]) -> Dict[str, Any]:
    """Validate the custom settings; returns the cleaned object."""
    if not isinstance(custom, dict):
        raise ValueError("'custom' must be an object")
    if "timeout_s" in custom and custom["timeout_s"] is not None:
        try:
            v = float(custom["timeout_s"])
        except (TypeError, ValueError):
            raise ValueError("'timeout_s' must be a number")
        if v <= 0 or v > 3600:
            raise ValueError("'timeout_s' must be between 1 and 3600")
        custom["timeout_s"] = int(v)
    if "max_tokens" in custom and custom["max_tokens"] is not None:
        try:
            v = float(custom["max_tokens"])
        except (TypeError, ValueError):
            raise ValueError("'max_tokens' must be a number")
        if v < 1024 or v > 65536:
            raise ValueError("'max_tokens' must be between 1024 and 65536")
        custom["max_tokens"] = int(v)
    return custom


EXCEL_GEN_CONFIG = ToolConfigDefinition(
    tool_name="use_excel_gen",
    display_name="Excel Generation",
    description=(
        "Generate an Excel spreadsheet (.xlsx) from a brief. "
        "Use when the user asks for an Excel file, spreadsheet, workbook, "
        "or wants data compiled into a table — e.g. turning web-search "
        "results into a clean sheet, building a concept/sample model with "
        "live formulas, or formatting data they provided in the conversation. "
        "Multiple sheets, headers, number formats, live Excel formulas, "
        "charts and a notes sheet are all supported. The workbook is "
        "generated by a specialized spreadsheet AI and saved as a "
        "downloadable file."
    ),
    model_task_slot="excel",
    custom_defaults={
        "timeout_s": DEFAULT_TIMEOUT_S,
        "max_tokens": DEFAULT_MAX_TOKENS,
    },
    custom_schema=[
        {
            "key": "generation",
            "label": "Generation",
            "fields": [
                ConfigField(
                    "timeout_s",
                    "Timeout (s)",
                    "int",
                    default=DEFAULT_TIMEOUT_S,
                    help="Per-attempt LLM call timeout for the JSON spec generation",
                ).to_dict(),
                ConfigField(
                    "max_tokens",
                    "Max tokens",
                    "int",
                    default=DEFAULT_MAX_TOKENS,
                    help="Output budget per LLM attempt — big workbooks need more",
                ).to_dict(),
            ],
        },
    ],
    validate_custom=_validate_excel_custom,
)

register_config(EXCEL_GEN_CONFIG)


# Register the tool
tool_registry.register(ExcelGenTool())
logger.info("[excel_gen_tool] ExcelGenTool registered")
